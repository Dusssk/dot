"""Generate custom python scripts for render jobs."""

import tempfile
import os
from typing import Dict, List
import logging


# If name has dots in it, it's imported as a part of a package
# (inside Blender), otherwise it's imported by the server script
# which needs absolute imports. Yeah, the module system sucks
if "." in __name__:
    from . import utils
else:
    import utils

log = logging.getLogger("batch.custom")


# Indent for code
TAB = " " * 4

formats = {
    "PNG": "PNG",
    "EXR": "OPEN_EXR",
    'OPEN_EXR': 'OPEN_EXR',
    "MULTILAYER": "OPEN_EXR_MULTILAYER",
    "JPEG": "JPEG",
    "JPEG2000": "JPEG2000",
    "TARGA": "TARGA",
    "TARGA_RAW": "TARGA_RAW",
    "CINEON": "CINEON",
    "DPX": "DPX",
    "BMP": "BMP",
    "IRIS": "IRIS",
    "HDR": "HDR",
    "TIF": "TIFF",
}


def enable_devices(index: int = None, only_GPU: bool = False) -> List:
    """Enable one or all GPUs."""

    code = ["addons = bpy.context.preferences.addons"]
    code += ['prefs = addons["cycles"].preferences']

    code += ['prefs.get_devices()']
    code += ['prefs.refresh_devices()']
    code += ['for i, device in enumerate(prefs.devices):']

    if not index:
        if only_GPU:
            code += [f'{TAB}if device.type != "CPU":']
            code += [f'{TAB}{TAB}device.use = True']
        else:
            code += [f'{TAB}device.use = True']
    else:
        code += [f'{TAB}device.use = True if device.id == "{index}" else False']

    code += [""]

    return code


def ttools_cache_folder(output: str, jid: int) -> str:
    """Generate cache folder for turbo tools."""

    base = tempfile.gettempdir()
    name = os.path.basename(output)

    return os.path.join(base, f"turboToolsCache_{name}_{jid}")


def build_passes_group(passes: list[dict]) -> List:
    """Build node group for renderpasses."""

    if not passes:
        return []

    output = ["nodes = scene.node_tree.nodes"]
    output += ["links = scene.node_tree.links"]
    output += ['render_node = nodes.new("CompositorNodeRLayers")']
    output += [""]

    # Enable Render passes
    for p in passes:
        key = p["key"]
        path = p["folder"]
        filename = p["filename"]
        socket = p["socket"]

        output += [f"viewlayer.{key} = True"]
        output += [f'file_output = nodes.new("CompositorNodeOutputFile")']

        output += [f'file_output.directory = "{path}"']
        output += [f'file_output.file_output_items[0].name = "{filename}"']

        output += [f'in_socket = render_node.outputs["{socket}"]']
        output += [f"out_socket = file_output.inputs[0]"]
        output += [f"links.new(in_socket, out_socket)"]

    output += []
    output += ["bpy.ops.wm.save_mainfile()"]

    return output


def build(job: Dict, settings: Dict) -> List:
    """Generate custom Py code for a render job."""

    scene = job["scene"]
    layer = job["layer"]
    output = job["output"].replace('\\', '\\\\')
    jid = job["id"]
    name = os.path.basename(output)
    is_local = (settings['type'] == 'LOCAL')

    code = [
        "# Custom Python script generated by Render+",
        "import bpy",
        "print('-' * 80)",
        "print('RENDERPLUS: Custom Code Start')",
        "print('-' * 80)",
        "bpy.context.preferences.use_preferences_save = False",
        "bpy.context.preferences.view.language = 'en_US'",
        f'scene = bpy.data.scenes["{scene}"]',
        f'scene.render.use_overwrite = {settings["overwrite"]}',
    ]

    if layer:
        code += [f'viewlayer = bpy.data.scenes["{scene}"].view_layers["{layer}"]']
    else:
        code += [f"viewlayer = bpy.context.view_layer"]

    if settings["disable_addons"]:
        code += [""]
        code += ["# Disable all addons for debugging"]
        code += ["from addon_utils import disable_all, enable"]
        code += ["disable_all()"]
        code += ['enable("cycles")']
        code += ['enable("Turbo Tools")']
        code += [""]

    if settings["global_size"]["enabled"]:
        size = settings["global_size"]["value"]
    elif job["size"]:
        size = job["size"]
    else:
        size = None

    if size:
        code += [f"scene.render.resolution_x = {size[0]}"]
        code += [f"scene.render.resolution_y = {size[1]}"]

    if job["world"]:
        code += [f'scene.world = bpy.data.worlds["{job["world"]}"]']

    if job["camera"]:
        code += [f'scene.camera = bpy.data.objects["{job["camera"]}"]']

    if job["layer"]:
        code += ["for l in scene.view_layers:"]
        code += [f'{TAB}l.use = (l.name == "{job["layer"]}")']

    if settings["global_percentage"]["enabled"]:
        percent = settings["global_percentage"]["value"]
        code += [f"scene.render.resolution_percentage = {percent}"]

    if settings["ignore_border"] and not job["section"]["enabled"]:
        code += ["scene.render.use_border = False"]

    if job["section"]["enabled"]:
        min_x = job["section"]["x"]
        min_y = job["section"]["y"]
        max_x = min(job["section"]["x"] + job["section"]["width"], 1)
        max_y = min(job["section"]["y"] + job["section"]["height"], 1)

        code += ["scene.render.use_border = True"]
        code += [f"scene.render.border_min_x = {min_x}"]
        code += [f"scene.render.border_min_y = {min_y}"]
        code += [f"scene.render.border_max_x = {max_x}"]
        code += [f"scene.render.border_max_y = {max_y}"]


    if job["cycles"]["samples"] > 0:
        code += [f'scene.cycles.aa_samples = {job["cycles"]["samples"]}']
        code += [f'scene.cycles.samples = {job["cycles"]["samples"]}']

    match job['cycles']['device']:
        case 'USE_ALL':
            code += ['scene.cycles.device = "GPU"']
            code += enable_devices()

        case 'CPU_ONLY':
            code += ['scene.cycles.device = "CPU"']

        case 'ALL_GPU':
            code += ['scene.cycles.device = "GPU"']
            code += enable_devices(only_GPU=True)

        case 'SINGLE_GPU' if is_local:
            code += ['scene.cycles.device = "GPU"']
            code += enable_devices(job['cycles']['device_number'])

        case 'SINGLE_GPU' if not is_local:
            code += enable_devices()
            code += ['scene.cycles.device = "GPU"']

    if job["custom_overrides"]:
        code += [""]
        code += ["# Custom Overrides"]

        for override in job["custom_overrides"]:
            if override["enabled"]:
                code += [""]
                code += [override['code']]

    # If the scene has some compositing going on, we need to keep the
    # Render Layers node updated to the current view layer
    if job["layer"] and settings["fix_layer_nodes"]:
        code += ["if scene.compositing_node_group.nodes:"]
        code += [f"{TAB}for node in scene.node_tree.nodes:"]
        code += [f"{TAB}{TAB}if node.bl_idname == 'CompositorNodeRLayers':"]
        code += [f'{TAB}{TAB}{TAB}node.layer = "{job["layer"]}"']

    code += ['']
    code += [f'scene.render.filepath = "{output}"']
    code += ['']

    if job["use_turbotools"]:
        code += [
            f'if scene.Turbo_Cache_Folder and scene.Turbo_Cache_Folder != "Please specify":'
        ]
        code += [rf'{TAB}scene.Turbo_Cache_Folder += "_{name}_{jid}"']
        code += [f"else:"]
        code += [
            rf'{TAB}scene.Turbo_Cache_Folder = r"{ttools_cache_folder(output, jid)}"'
        ]
        code += [""]
        code += [f'scene.frame_start = {job["frame_start"]}']
        code += [f'scene.frame_end = {job["frame_end"]}']
        code += [f'scene.frame_step = {job["frame_jump"]}']
        code += [f'scene.frame_current = {job["frames"]}']
        code += [
            f'scene.render.image_settings.file_format = "{formats[job["format"]]}"'
        ]
        code += [""]

        if job["animated"]:
            code += ["bpy.ops.threedi.render_animation()"]
        else:
            code += ["bpy.ops.threedi.render_still(write_still=True)"]

    if job["render_passes"]:
        code += [""]
        code += build_passes_group(job["render_passes"])

    code += ["bpy.context.view_layer.update()"]
    code += [""]
    code += ["def render_complete_handler(scene):"]
    code += [f"{TAB}print('RENDERPLUS: job completed.')"]
    code += [""]
    code += ["bpy.app.handlers.render_complete.append(render_complete_handler)"]
    code += [""]

    return code


def filepath(blend: str, job_name: str, jid: int, sys: str, base: str) -> str:
    """Get path/filename to custom py for a render job."""

    blend = utils.strip_extension(blend, sys)
    job_name = utils.strip_extension(job_name, sys)
    filename = f"{blend}_{job_name}_{jid}_{utils.stamp_suffix()}.py"

    return os.path.join(base, filename)


def write(job: Dict, name: str, settings: Dict) -> str:
    """Write custom python code for render job."""

    py_path = filepath(name, job["blend_file"], job["id"],
                       settings["OS"], settings['temp'])
    py_code = build(job, settings)

    log.debug(f"Path to custom py is {py_path}")
    log.debug(f"Generated custom py is {py_code}")

    with open(py_path, "w", encoding='utf-8') as stream:
        stream.write("\n".join(py_code))

    return py_path
